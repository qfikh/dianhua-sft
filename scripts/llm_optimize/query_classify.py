def replace_role_prefix():
    file_path = "/Users/xujianjun/workspace/dianhua-sft/data/origin_data/0722人人-人机-生成-整体待标注数据_添加客户意图_0722_61592.xlsx"
    df = pd.read_excel(file_path, sheet_name="Sheet1")
    
    not_client_end_count = 0
    
    def replace_prefix(text):
        nonlocal not_client_end_count
        if pd.isna(text):
            return text
        text = str(text)
        if 'Service' in text or 'service' in text:
            text = text.replace('Service:', '客服：').replace('Service：', '客服：')
            text = text.replace('service:', '客服：').replace('service：', '客服：')
        if 'Client' in text or 'client' in text:
            text = text.replace('Client:', '客户：').replace('Client：', '客户：')
            text = text.replace('client:', '客户：').replace('client：', '客户：')
        
        lines = text.split('\n')
        lines = [line for line in lines if line.strip()]
        if lines:
            last_line = lines[-1].strip()
            if not last_line.startswith('客户：'):
                not_client_end_count += 1
                return None
        return text
    
    original_count = len(df)
    df['对话片段'] = df['对话片段'].apply(replace_prefix)
    df = df.dropna(subset=['对话片段'])
    print(f"原始数据共 {original_count} 条")
    print(f"共过滤掉 {not_client_end_count} 条不以客户结尾的对话数据")
    print(f"过滤后剩余 {len(df)} 条数据")
    df.to_excel(file_path, index=False)
    print(f"角色前缀替换完成，结果已保存至: {file_path}")


